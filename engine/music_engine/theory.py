def list_topics():
    return [{"id": k, "title": v["title"], "summary": v["summary"]} for k, v in TOPICS.items()]


def read(topic=None, section=None):
    """返回可读文本；topic 为空时返回目录。"""
    if not topic:
        lines = ["乐理速查目录（先读再写，别凭感觉堆和弦）："]
        for t in list_topics():
            lines.append(f"- {t['id']}：{t['title']} —— {t['summary']}")
        lines.append("\n用法：music_theory(topic=\"progressions\")，可再传 section 只看某一组。")
        return {"ok": True, "topics": list_topics(), "text": "\n".join(lines)}

    item = TOPICS.get(topic)
    if not item:
        raise ValueError(f"没有乐理条目 {topic}；可用：" + "、".join(TOPICS))
    chosen = item["sections"]
    if section:
        chosen = [s for s in chosen if section in s[0]]
        if not chosen:
            raise ValueError(f"{topic} 没有分组 {section}；可选：" +
                             "、".join(s[0] for s in item["sections"]))
    lines = [f"# {item['title']}", item["summary"], ""]
    for head, points in chosen:
        lines.append(f"## {head}")
        for p in points:
            lines.append(f"- {p}")
        lines.append("")
    return {"ok": True, "topic": topic, "title": item["title"], "text": "\n".join(lines).strip()}
